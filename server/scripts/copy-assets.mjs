#!/usr/bin/env node
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const serverDir = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(serverDir, "src");
const build = join(serverDir, "build");
const repoRoot = dirname(serverDir);

mkdirSync(build, { recursive: true });
copyFileSync(join(src, "icon.svg"), join(build, "icon.svg"));
copyFileSync(join(src, "favicon.ico"), join(build, "favicon.ico"));
copyFileSync(join(repoRoot, "README.md"), join(serverDir, "README.md"));

// Inject real build metadata into build/build-info.js (overwrites the tsc-compiled dev defaults).
const pkg = JSON.parse(readFileSync(join(serverDir, "package.json"), "utf8"));
let commit = "dev";
try {
  commit = execSync("git rev-parse --short HEAD", { cwd: repoRoot, stdio: ["pipe", "pipe", "ignore"] })
    .toString()
    .trim();
} catch {
  // git unavailable (e.g. CI artifact build) — keep "dev"
}
writeFileSync(
  join(build, "build-info.js"),
  `// Auto-generated by scripts/copy-assets.mjs — do not edit.\nexport const BUILD_INFO = ${JSON.stringify({ version: pkg.version, built: new Date().toISOString(), commit })};\n`
);

